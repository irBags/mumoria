local DEAD = {"Skeleton Human", "Human Zombie", "Moaning Spirit", "Skeleton Hobgoblin", "Mummified Orc"}

local function far(a, b)
  return math.max(math.abs(a.x - b.x), math.abs(a.y - b.y))
end

-- the tombs near `at` that have not opened yet open, and their dead climb out
local function wake(d, at)
  d.flags.woken = d.flags.woken or {}
  local n = 0
  for i, t in ipairs(d.places.T) do
    if not d.flags.woken[i] and far(t, at) <= 9 then
      d.flags.woken[i] = true
      mu.spawn{creature = DEAD[mu.random(#DEAD)], at = t, awake = true}
      n = n + 1
    end
  end
  if n > 0 then mu.say_level("[Crypt] Stone grinds on stone. " .. n .. " tomb(s) open, and the dead climb out.") end
end

local function blink(m, d)
  local c = d.places.c[mu.random(#d.places.c)]
  mu.teleport(m, c)
end

local lich_d -- the copy whose Lich is being hurt

local LICH_PHASES = {
  {at = 66, run = function(m)
    mu.say_level("The Lich hisses: \"Rise, my servants!\" It fades, and appears by a coffin.")
    mu.spawn{creature = "Skeleton Human", near = m, count = 3, awake = true}
    blink(m, lich_d)
  end},
  {at = 33, run = function(m)
    mu.say_level("The Lich drinks the cold of the grave. Wights answer its call!")
    mu.heal(m, m.max_hp // 5)
    mu.spawn{creature = "Forest Wight", near = m, count = 2, awake = true}
    blink(m, lich_d)
  end},
}

mu.dungeon{
  key = KEY,
  name = "the Crypt of the Lich",
  label = "Lich's Crypt",
  depth = 22,
  level = {15, 25},
  about = "tombs that wake, a sealed door and its key, and the Lich below.",
  map = MAP,
  legend = {
    D = "#",
    u = {spawn = {creature = "Forest Wight"}},
  },
  build = function(d)
    mu.spawn{creature = "Lich", at = d.places.L[1], boss = "lich", hp = 1.5 * (1 + (d.party - 1) / 2)}
    for _, at in ipairs(d.places.H) do mu.drop("rare", at) end
  end,
  enter = function(p, d)
    mu.tell(p, "[Crypt] Cold air rises from below. Rows of tombs line the hall ahead, and every one is sealed.")
  end,
  step = function(p, d, letter, at)
    if letter == "x" or letter == "y" then
      wake(d, at)
    elseif letter == "S" and not d.flags.key then
      d.flags.key = true
      mu.say_level("[Crypt] " .. p.name .. " heaves the sarcophagus lid aside: a bone key! Something within stirs...")
      mu.spawn{creature = "Mummified Orc", name = "Tomb Guardian", near = at, hp = 3, awake = true}
      for _, door in ipairs(d.places.D) do mu.tile(door, ",") end
      mu.say_level("[Crypt] Far off, a sealed door grinds open.")
    end
  end,
  hurt = function(p, m, d)
    if m.boss == "lich" then
      lich_d = d
      mu.phases(m, LICH_PHASES)
    end
  end,
  kill = function(p, m, d)
    if m.boss ~= "lich" then return end
    mu.drop("epic", d.places.H[2])
    mu.say_level("[Crypt] The Lich crumbles to dust with a fading wail. Its treasure lies at the chamber's south wall.")
    mu.say_world(p.name .. (d.party > 1 and "'s party has" or " has") .. " destroyed the Lich!")
    mu.reward_party{key = KEY, title = TITLE, tier = "epic", gold = 900,
                    items = {{key = "lich_robe", name = "the Robe of the Deathless", one_in = 3}}}
  end,
}
