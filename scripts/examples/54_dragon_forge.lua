local WYRM_PHASES = {
  {at = 75, run = function(m)
    mu.say_level("Ignaroth roars, and her brood answers from the dark!")
    mu.spawn{creature = "Young Red Dragon", near = m, count = 2, awake = true}
  end},
  {at = 50, run = function(m)
    mu.say_level("Ignaroth beats her wings over the forge-fires. Living flame pours out!")
    mu.spawn{creature = "Fire Elemental", near = m, count = 3, awake = true}
  end},
  {at = 25, run = function(m)
    mu.say_level("Ignaroth bathes in the molten forge, her wounds sealing over!")
    mu.heal(m, m.max_hp * 15 // 100)
    mu.spawn{creature = "Giant Fire Bat", near = m, count = 3, awake = true}
  end},
}

mu.dungeon{
  key = KEY,
  name = "the Dragon's Forge",
  label = "Dragon's Forge",
  depth = 34,
  level = {30, 40},
  about = "magma halls, a drake gauntlet, three forge-keepers, and Ignaroth the Forge-Wyrm.",
  map = MAP,
  legend = {
    G = "%",
    h = "%",
    d = {spawn = {creature = "Young Red Dragon"}},
    t = {spawn = {creature = "Giant Fire Tick"}},
    f = {spawn = {creature = "Fire Spirit"}},
    B = {spawn = {creature = "Killer Fire Beetle"}},
    e = {spawn = {creature = "Red Dragon Bat"}},
  },
  build = function(d)
    for _, at in ipairs(d.places.E) do
      mu.spawn{creature = "Fire Elemental", name = "Forge-Keeper", at = at, tag = "forge_keeper", hp = 3}
    end
    mu.spawn{creature = "Mature Red Dragon", name = "Ignaroth the Forge-Wyrm", at = d.places.W[1], boss = "ignaroth",
             hp = 3 * (1 + (d.party - 1) / 2), speed = 1}
  end,
  enter = function(p, d)
    mu.tell(p, "[Forge] Heat hammers at you. Deep within, something vast breathes like a bellows.")
  end,
  hurt = function(p, m, d)
    if m.boss == "ignaroth" then mu.phases(m, WYRM_PHASES) end
  end,
  kill = function(p, m, d)
    if m.tag == "forge_keeper" then
      local left = #mu.tagged("forge_keeper")
      if left > 0 then
        mu.say_level("[Forge] A forge gutters out. " .. left .. " still burn.")
      else
        for _, at in ipairs(d.places.G) do mu.tile(at, ".") end
        mu.say_level("[Forge] The last forge dies. With a crack like thunder, the great door to the wyrm's hall cools and swings open.")
      end
    elseif m.boss == "ignaroth" then
      for _, at in ipairs(d.places.h) do mu.tile(at, ".") end
      for i, at in ipairs(d.places.V) do mu.drop(i == 3 and "legendary" or "epic", at) end
      mu.say_level("[Forge] Ignaroth falls, and the forge's heart goes cold. The seal on her hoard (north) cracks open.")
      mu.say_world(p.name .. (d.party > 1 and "'s party has" or " has") .. " slain Ignaroth the Forge-Wyrm!")
      mu.reward_party{key = KEY, title = TITLE, tier = "epic", gold = 2500,
                      items = {{key = "wyrmforged_blade", name = "the Wyrmforged Blade", one_in = 4}}}
    end
  end,
}
